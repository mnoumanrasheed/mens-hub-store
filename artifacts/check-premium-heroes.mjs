import { chromium, expect } from '@playwright/test';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const base = process.env.HERO_BASE_URL || 'http://localhost:3001';
const errors = [];
const results = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
  page.on('pageerror', error => errors.push(error.message));
  const visit = async (path) => {
    const response = await page.goto(base + path, { waitUntil: 'networkidle', timeout: 60000 });
    expect(response.status()).toBe(200);
    await page.locator('.initial-storefront-loader').waitFor({ state: 'hidden', timeout: 15000 });
    await page.locator('[data-store-hero]').waitFor();
    await page.waitForTimeout(2000);
    return page.locator('[data-store-hero]');
  };
  await visit('/shop');
  const category = await page.locator('.collection-category-nav a').nth(1).getAttribute('href');
  expect(category).toBeTruthy();
  const routes = ['/shop', category, '/new-arrivals', '/sale', '/about', '/contact'];
  for (const path of routes) {
    const hero = await visit(path);
    const atmosphere = hero.locator('.store-hero-atmosphere');
    await expect(atmosphere).toHaveAttribute('data-live', 'true');
    expect(await hero.locator('canvas').count()).toBe(0);
    expect(await hero.getByText('MH', { exact: true }).count()).toBe(0);
    expect(await hero.locator('.store-hero-brand-mark img').getAttribute('src')).toContain('logo.png');
    const opacity = await hero.locator('.store-hero-brand-mark').evaluate(el => Number(getComputedStyle(el).opacity));
    expect(opacity).toBeGreaterThanOrEqual(.03); expect(opacity).toBeLessThanOrEqual(.08);
    const transforms = () => atmosphere.locator('.store-hero-brand-mark, .store-hero-ambient, .store-hero-depth, .store-hero-light-sweep').evaluateAll(nodes => nodes.map(el => getComputedStyle(el).transform));
    const before = await transforms();
    const boxBefore = await hero.locator('h1').boundingBox();
    await page.waitForTimeout(1400);
    const after = await transforms();
    for (let i=0;i<before.length;i++) expect(after[i], path + ' live layer ' + i).not.toBe(before[i]);
    expect(await hero.locator('h1').boundingBox()).toEqual(boxBefore);
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
    if (['/shop','/about','/contact'].includes(path)) await page.screenshot({ path: 'artifacts/premium-hero-' + path.slice(1) + '-desktop.png' });
    await page.setViewportSize({ width:390, height:844 });
    await page.waitForTimeout(500);
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
    expect(await hero.locator('.store-hero-brand-mark').evaluate(el => Number(getComputedStyle(el).opacity))).toBe(.04);
    if (['/shop','/about','/contact'].includes(path)) await page.screenshot({ path: 'artifacts/premium-hero-' + path.slice(1) + '-mobile.png' });
    await page.setViewportSize({ width:320, height:740 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
    await page.emulateMedia({ reducedMotion:'reduce' });
    await expect(atmosphere).toHaveAttribute('data-live','false');
    await page.waitForTimeout(100);
    const reducedBefore = await transforms();
    await page.waitForTimeout(350);
    expect(await transforms()).toEqual(reducedBefore);
    expect(await atmosphere.locator('.store-hero-light-sweep').evaluate(el => getComputedStyle(el).opacity)).toBe('0');
    expect(await hero.locator('h1').isVisible()).toBe(true);
    results.push({ path, continuous:true, logoOpacity:opacity, mobile:true, reducedMotion:true, noHeroCanvas:true });
    console.log(JSON.stringify(results.at(-1)));
    await page.emulateMedia({ reducedMotion:'no-preference' });
    await page.setViewportSize({ width:1440,height:960 });
  }
  const hero=page.locator('[data-store-hero]');
  await page.evaluate(() => window.scrollTo({ top:document.body.scrollHeight, behavior:'instant' }));
  await expect(hero.locator('.store-hero-atmosphere')).toHaveAttribute('data-live','false');
  await page.evaluate(() => window.scrollTo({ top:0, behavior:'instant' }));
  await expect(hero.locator('.store-hero-atmosphere')).toHaveAttribute('data-live','true');
  await page.context().route('https://wa.me/**', route => route.fulfill({status:200,body:'Local draft preview'}));
  await page.context().route('**/api/analytics/events', route => route.fulfill({status:200,body:'{}'}));
  await page.getByText('Order support',{exact:true}).click();
  await page.getByLabel('Your name').fill('Hero review');
  await page.getByLabel('Your message').fill('Please help with sizing.');
  const popupPromise=page.context().waitForEvent('page');
  await page.getByRole('button',{name:'Continue on WhatsApp'}).click();
  const popup=await popupPromise;await popup.waitForLoadState('domcontentloaded');
  expect(new URL(popup.url()).searchParams.get('text')).toContain('Order support');
  await popup.close();
  await visit('/shop');
  await page.getByRole('navigation',{name:'Main navigation',exact:true}).getByRole('link',{name:'Sale',exact:true}).click();
  await expect(page.locator('[data-store-hero] h1')).toHaveText('Sale');
  await expect(page.locator('.store-hero-atmosphere')).toHaveAttribute('data-live','true');
  expect(errors).toEqual([]);
  console.log(JSON.stringify({ results, offscreenSuspension:true, whatsappDraft:true, clientNavigation:true, errors }));
} finally { await browser.close(); }
